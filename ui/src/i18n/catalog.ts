export function translate(language: Language, text: string, variables: Variables = {}): string {
  const key = Object.hasOwn(aliases, text) ? aliases[text] : text;
  let value = language === 'zh-CN' ? (Object.hasOwn(zh, key) ? zh[key] : key) : key;
  if (language === 'zh-CN' && !zh[key]) {
    // These patterns are only used by UI labels/placeholders, never user content.
    value = value.replace(/^(Picture|Image) (\d+)$/, '参考图 $2')
      .replace(/^Dataset (\d+)$/, '数据集 $1')
      .replace(/^Control Dataset (\d+)$/, '参考数据集 $1')
      .replace(/ \(default\)$/, '（默认）')
      .replace(/^eg\. /, '例如：');
  }
  return value.replace(/\{(\w+)\}/g, (match, name) => Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match);
}
